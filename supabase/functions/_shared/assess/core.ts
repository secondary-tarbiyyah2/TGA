// Core types and helpers for the TGA entry assessment.
//
// Everything in /assess is pure TypeScript (no Deno or Node APIs), so the same
// code generates papers in the Edge Function and runs under `node
// --experimental-strip-types` in scripts/assess-selftest.ts.
//
// An Item is generated on the server from a seed and stored WITH its answer in
// assessment_sittings.form (service role only). What the candidate's browser
// receives is a PublicItem: the same thing with `answer` and `meta` removed.

export type Strand =
  | "maths"
  | "reading"
  | "spelling"
  | "grammar"
  | "phonics"
  | "verbal"
  | "quantitative"
  | "nonverbal";

export type ItemType = "mcq" | "numeric" | "text";

export type Item = {
  id: string;
  strand: Strand;
  /** National-curriculum year at which a typical pupil gets this right ~60–70% of the time. */
  level: number;
  /** Short label for the report's "gaps" list, e.g. "Y4 multiply 2-digit by 1-digit". */
  objective: string;
  type: ItemType;
  stem: string;
  /** Inline SVG shown above the choices (diagrams, shape puzzles). Generated by us, never user input. */
  svg?: string;
  /** For picture-choice puzzles: each choice is an SVG. */
  choiceSvgs?: string[];
  choices?: string[];
  /** Words read aloud by the browser (speech synthesis) · phonics and young-reader support. */
  say?: string;
  /** Reading passages: the passage id this question belongs to (passage text is sent once per section). */
  passageId?: string;
  /** Numeric: the unit shown after the box, e.g. "cm" or "£". */
  unit?: string;
  answer: string | number;
  /** Numeric tolerance (absolute). */
  tolerance?: number;
  /** Text answers that also count as right (case/space-insensitive). */
  accept?: string[];
  /**
   * Read-aloud: false when reading the options out would give the answer away
   * (phonics: the child must find the word they heard; spelling: a voice reads
   * a misspelling and the right spelling the same way). The stem is still read.
   */
  speakChoices?: boolean;
  /** Read-aloud: speak punctuation marks and capital letters in the options (punctuation questions). */
  speakPunctuation?: boolean;
};

export type PublicItem = Omit<Item, "answer" | "tolerance" | "accept">;

export function toPublic(item: Item): PublicItem {
  // eslint-disable-next-line @typescript-eslint/no-unused-vars -- these keys are removed on purpose
  const { answer: _a, tolerance: _t, accept: _c, ...rest } = item;
  return rest;
}

// ── seeded randomness ──────────────────────────────────────────────────────
// mulberry32: tiny, fast and good enough for shuffling questions. The seed is
// stored on the sitting so a paper can always be regenerated exactly.
export class Rng {
  private s: number;
  constructor(seed: number) {
    this.s = seed >>> 0 || 1;
  }
  next(): number {
    let t = (this.s += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  int(lo: number, hi: number): number {
    return lo + Math.floor(this.next() * (hi - lo + 1));
  }
  pick<T>(arr: readonly T[]): T {
    return arr[Math.floor(this.next() * arr.length)];
  }
  shuffle<T>(arr: readonly T[]): T[] {
    const a = [...arr];
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(this.next() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }
  /** Pick n distinct items. */
  sample<T>(arr: readonly T[], n: number): T[] {
    return this.shuffle(arr).slice(0, Math.min(n, arr.length));
  }
  chance(p: number): boolean {
    return this.next() < p;
  }
}

export function hashSeed(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/**
 * Shuffle a correct answer in among distractors; returns the choices and the
 * answer as the choice TEXT (so marking never depends on position).
 * Distractors equal to the answer, or to each other, are dropped and refilled
 * from `spare` so every choice is distinct.
 */
export function mcq(rng: Rng, correct: string, distractors: string[], spare: string[] = [], n = 4): { choices: string[]; answer: string } {
  // Exact comparison (only outer spaces ignored): grammar options often differ by a single capital letter.
  const seen = new Set([correct.trim()]);
  const ds: string[] = [];
  for (const d of [...distractors, ...rng.shuffle(spare)]) {
    const k = d.trim();
    if (!seen.has(k) && d !== "") {
      seen.add(k);
      ds.push(d);
    }
    if (ds.length >= n - 1) break;
  }
  return { choices: rng.shuffle([correct, ...ds]), answer: correct };
}

export const norm = (s: string): string => s.trim().toLowerCase().replace(/\s+/g, " ").replace(/[’']/g, "'");

/** Numeric distractors near the answer: off-by-one, place-value slips, common errors. */
export function numericDistractors(rng: Rng, ans: number, extra: number[] = []): string[] {
  const cands = new Set<number>(extra.filter((x) => Number.isFinite(x) && x !== ans));
  const step = Math.max(1, Math.round(Math.abs(ans) * 0.1));
  for (const d of [ans + 1, ans - 1, ans + step, ans - step, ans * 10, Math.round(ans / 10), ans + 10, ans - 10, ans + 2]) {
    if (d !== ans && Number.isFinite(d)) cands.add(d);
  }
  return rng.shuffle([...cands]).slice(0, 6).map(fmt);
}

// ── powers ─────────────────────────────────────────────────────────────────
// Powers are written with real superscript characters (x⁵, 10⁻³), never "x^5",
// so they read correctly anywhere the text is shown (sitting page, staff
// views, emails). The browser renderer also turns any older "^n" into <sup>.
const SUP: Record<string, string> = { "0": "⁰", "1": "¹", "2": "²", "3": "³", "4": "⁴", "5": "⁵", "6": "⁶", "7": "⁷", "8": "⁸", "9": "⁹", "-": "⁻", "−": "⁻", n: "ⁿ" };
export const sup = (e: number | string): string => String(e).split("").map((c) => SUP[c] ?? c).join("");

/** Round away floating-point noise (4.7 × 1000 = 4700.000000000001). */
export const clean = (n: number, dp = 6): number => Math.round(n * 10 ** dp) / 10 ** dp;

/** Numbers as shown to pupils: thousands commas, and a proper minus sign (−) for negatives. */
export function fmt(n: number): string {
  n = clean(n);
  if (n < 0) return `−${fmt(-n)}`;
  if (Number.isInteger(n)) return n.toLocaleString("en-GB");
  return String(Math.round(n * 1000) / 1000);
}

export function markItem(item: Item, response: unknown): boolean {
  if (response === null || response === undefined || response === "") return false;
  if (item.type === "numeric") {
    const v = Number(String(response).replace(/[,£\s]/g, "").replace(/[−–]/g, "-").replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660)));
    if (!Number.isFinite(v)) return false;
    return Math.abs(v - Number(item.answer)) <= (item.tolerance ?? 1e-9);
  }
  // Multiple choice: the exact option (capitals and punctuation matter in grammar questions).
  if (item.type === "mcq") return String(response).trim() === String(item.answer).trim();
  const r = norm(String(response));
  if (r === norm(String(item.answer))) return true;
  return (item.accept || []).some((a) => norm(a) === r);
}
