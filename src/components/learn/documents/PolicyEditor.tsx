"use client";

import { absoluteFileUrl } from "@/lib/learn/fileLinks";
import { useCallback, useEffect, useState } from "react";
import { Card } from "@/components/learn/Card";
import { getPolicyLinks } from "@/lib/content";
import { DOCX_MIME, UPLOAD_ACCEPT, extractDocxText, storageObjectName, uploadKind, uploadProblem } from "@/lib/learn/documentUpload";
import { getSupabaseClient } from "@/lib/supabase/client";
import { ui } from "@/components/learn/ui";

type Row = {
  id: string;
  number: string;
  title: string;
  category: "required" | "published";
  parent_question_category: string | null;
  file_url: string;
  summary: string | null;
  last_reviewed: string | null;
  next_review: string | null;
  order_index: number;
  deleted_at: string | null;
  slug: string | null;
  file_path: string | null;
  file_name: string | null;
  file_kind: "pdf" | "docx" | null;
  file_updated_at: string | null;
  extracted_text: string | null;
  visibility: "public" | "staff";
  featured: boolean;
};

type Draft = Omit<Row, "id" | "deleted_at" | "slug">;

const BLANK: Draft = {
  number: "", title: "", category: "required", parent_question_category: null, file_url: "", summary: null, last_reviewed: null, next_review: null, order_index: 0,
  file_path: null, file_name: null, file_kind: null, file_updated_at: null, extracted_text: null,
  visibility: "public", featured: false,
};

/** The permanent address of an uploaded policy on the main site. */
const stableUrl = (slug: string, kind: "pdf" | "docx") => `/policies/${slug}.${kind}`;
/** Placeholder address while a brand-new policy's slug is being generated by the database. */
const PENDING_URL = "/policies/pending";
/** The parent-question headings on the public Policies page (PolicyDirectory). */
const GROUPS: { key: string; label: string }[] = [
  { key: "safety", label: "Is my child safe?" },
  { key: "admissions-fees", label: "How do we apply, and what does it cost?" },
  { key: "complaints", label: "What if something goes wrong?" },
  { key: "data", label: "How is my data used?" },
  { key: "curriculum", label: "What do you teach, and how?" },
];
const inputCls = `mt-1 ${ui.input}`;

/**
 * Website policy editor ("Policy documents" in Website content).
 *
 * Reads policy_links directly (the same table getPolicyLinks() reads for the
 * public site). The old generic editor showed "Nothing here yet" because
 * that table was never seeded, so the website fell back to the bundled
 * seed.ts list while the editor saw zero rows; migration 0047 seeds it, and
 * the Import button below covers any database where it still is empty.
 * "Remove" is a soft delete (deleted_at): the public read policy hides it
 * and it can be restored here.
 */
export function PolicyEditor() {
  const supabase = getSupabaseClient();
  const [rows, setRows] = useState<Row[] | null>(null);
  const [editingId, setEditingId] = useState<string | "new" | null>(null);
  const [draft, setDraft] = useState<Draft>(BLANK);
  const [editingSlug, setEditingSlug] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState<{ text: string; error?: boolean } | null>(null);
  const [showRemoved, setShowRemoved] = useState(false);

  const load = useCallback(async () => {
    if (!supabase) return;
    const { data, error } = await supabase.from("policy_links").select("*").order("order_index");
    if (error) setMessage({ text: `Could not load policies: ${error.message}`, error: true });
    setRows((data as Row[]) || []);
  }, [supabase]);

  useEffect(() => {
    // eslint-disable-next-line react-hooks/set-state-in-effect -- initial data load
    load();
  }, [load]);

  const live = (rows || []).filter((r) => !r.deleted_at);
  const removed = (rows || []).filter((r) => r.deleted_at);

  // Policies are read live by the website (no rebuild), so a save is final.
  const liveMessage = (prefix: string) => setMessage({ text: `${prefix} Changes are live immediately.` });

  const startEdit = (r: Row) => {
    setEditingId(r.id);
    setEditingSlug(r.slug);
    setDraft({
      number: r.number, title: r.title, category: r.category, parent_question_category: r.parent_question_category, file_url: r.file_url,
      summary: r.summary, last_reviewed: r.last_reviewed, next_review: r.next_review, order_index: r.order_index,
      file_path: r.file_path, file_name: r.file_name, file_kind: r.file_kind, file_updated_at: r.file_updated_at, extracted_text: r.extracted_text,
      visibility: r.visibility || "public", featured: !!r.featured,
    });
    setMessage(null);
  };
  const startNew = () => {
    setEditingId("new");
    setEditingSlug(null);
    setDraft({ ...BLANK, order_index: (live[live.length - 1]?.order_index ?? 0) + 1 });
    setMessage(null);
  };

  const set = <K extends keyof typeof draft>(k: K, v: (typeof draft)[K]) => setDraft((d) => ({ ...d, [k]: v }));

  async function upload(file: File) {
    if (!supabase) return;
    const problem = uploadProblem(file);
    if (problem) return setMessage({ text: problem, error: true });
    const kind = uploadKind(file);
    if (!kind) return;
    setBusy(true);
    let text: string | null = null;
    let warning = "";
    if (kind === "docx") {
      try {
        text = (await extractDocxText(file)) || null;
      } catch {
        text = null;
      }
      if (!text) warning = " The text could not be read from this Word file, so it cannot be previewed when people sign it. A PDF avoids this.";
    }
    const path = `${editingSlug || "new"}/${storageObjectName(file)}`;
    const { error } = await supabase.storage.from("policy-documents").upload(path, file, { contentType: kind === "pdf" ? "application/pdf" : DOCX_MIME, upsert: false });
    if (error) {
      setBusy(false);
      return setMessage({ text: `Upload failed: ${error.message}. Only a Headteacher or Admin can upload.`, error: true });
    }
    setDraft((d) => ({
      ...d,
      file_path: path,
      file_name: file.name,
      file_kind: kind,
      file_updated_at: new Date().toISOString(),
      extracted_text: text,
      file_url: editingSlug ? stableUrl(editingSlug, kind) : PENDING_URL,
    }));
    setBusy(false);
    setMessage({ text: `Uploaded.${warning} Press Save to put it on the website.` });
  }

  function removeUpload() {
    setDraft((d) => ({ ...d, file_path: null, file_name: null, file_kind: null, file_updated_at: null, extracted_text: null, file_url: "" }));
  }

  // A policy's signature record follows its title and file automatically (a
  // database trigger, migration 0086); only "remove" has to stop the asking.
  async function stopAskingToSign(id: string) {
    if (!supabase) return;
    await supabase.from("signable_documents").update({ requires_signature: false }).eq("sanity_document_id", `policy:${id}`).eq("source", "policy");
  }

  async function save() {
    if (!supabase) return;
    if (!draft.number.trim() || !draft.title.trim()) return setMessage({ text: "Policy number and title are required.", error: true });
    const uploaded = !!draft.file_path && !!draft.file_kind;
    if (!uploaded && !draft.file_url.trim()) return setMessage({ text: "Upload a PDF or Word file, or add a link to the file.", error: true });
    if (!uploaded && !/^(https:\/\/|\/)/i.test(draft.file_url.trim())) return setMessage({ text: "The link must start with https:// or /", error: true });
    setBusy(true);
    const isNew = editingId === "new";
    const payload = {
      ...draft,
      number: draft.number.trim(),
      title: draft.title.trim(),
      file_url: uploaded && draft.file_kind ? (editingSlug ? stableUrl(editingSlug, draft.file_kind) : PENDING_URL) : draft.file_url.trim(),
      summary: draft.summary?.trim() || null,
      last_reviewed: draft.last_reviewed || null,
      next_review: draft.next_review || null,
      updated_at: new Date().toISOString(),
    };
    let error: { message: string } | null = null;
    if (isNew) {
      const res = await supabase.from("policy_links").insert(payload).select("id, slug").single();
      error = res.error;
      const created = res.data as { id: string; slug: string | null } | null;
      // The database picks the permanent address (slug); point the uploaded file at it.
      if (!error && uploaded && draft.file_kind && created?.slug) {
        const fix = await supabase.from("policy_links").update({ file_url: stableUrl(created.slug, draft.file_kind) }).eq("id", created.id);
        error = fix.error;
      }
    } else {
      const res = await supabase.from("policy_links").update(payload).eq("id", editingId);
      error = res.error;
    }
    if (error) {
      setBusy(false);
      return setMessage({ text: `Could not save: ${error.message}`, error: true });
    }
    setEditingId(null);
    await load();
    liveMessage("Saved.");
    setBusy(false);
  }

  async function remove(r: Row) {
    if (!supabase) return;
    if (!confirm(`Remove "${r.title}" from the website? It stops being listed publicly and nobody is asked to sign it. You can restore it later.`)) return;
    setBusy(true);
    const { data: u } = await supabase.auth.getUser();
    const { error } = await supabase.from("policy_links").update({ deleted_at: new Date().toISOString(), deleted_by: u.user?.id ?? null }).eq("id", r.id);
    if (error) {
      setBusy(false);
      return setMessage({ text: `Could not remove: ${error.message}`, error: true });
    }
    await stopAskingToSign(r.id);
    await load();
    liveMessage("Removed.");
    setBusy(false);
  }

  async function restore(r: Row) {
    if (!supabase) return;
    setBusy(true);
    const { error } = await supabase.from("policy_links").update({ deleted_at: null, deleted_by: null }).eq("id", r.id);
    if (error) setMessage({ text: `Could not restore: ${error.message}`, error: true });
    else {
      await load();
      liveMessage("Restored.");
    }
    setBusy(false);
  }

  /** Swap display order with the neighbour above/below, so the public list reorders without typing numbers. */
  async function move(r: Row, dir: -1 | 1) {
    if (!supabase) return;
    const i = live.findIndex((x) => x.id === r.id);
    const other = live[i + dir];
    if (!other) return;
    setBusy(true);
    const a = other.order_index === r.order_index ? r.order_index + dir : other.order_index;
    const b = other.order_index === r.order_index ? r.order_index : r.order_index;
    const res1 = await supabase.from("policy_links").update({ order_index: a, updated_at: new Date().toISOString() }).eq("id", r.id);
    const res2 = await supabase.from("policy_links").update({ order_index: b, updated_at: new Date().toISOString() }).eq("id", other.id);
    if (res1.error || res2.error) setMessage({ text: `Could not reorder: ${(res1.error || res2.error)?.message}`, error: true });
    await load();
    setBusy(false);
  }

  /** Website / staff-only without opening the whole form. */
  async function setVisibility(r: Row, visibility: Row["visibility"]) {
    if (!supabase) return;
    setBusy(true);
    const { error } = await supabase.from("policy_links").update({ visibility, updated_at: new Date().toISOString() }).eq("id", r.id);
    if (error) setMessage({ text: `Could not change visibility: ${error.message}`, error: true });
    else {
      await load();
      liveMessage(visibility === "public" ? "Now listed on the website." : "Now staff-only: kept for signing and compliance, not listed on the website.");
    }
    setBusy(false);
  }

  async function importCurrent() {
    if (!supabase) return;
    setBusy(true);
    const current = await getPolicyLinks();
    const { error } = await supabase.from("policy_links").insert(
      current.map((p, i) => ({
        number: p.number, title: p.title, category: p.category, parent_question_category: p.parentQuestionCategory ?? null, file_url: p.fileUrl,
        slug: p.fileUrl.match(/^\/policies\/([a-z0-9][a-z0-9-]*)\.(?:pdf|docx)$/)?.[1] ?? null,
        summary: p.summary ?? null, last_reviewed: p.lastReviewed ?? null, next_review: p.nextReview ?? null, order_index: p.order ?? i + 1,
      })),
    );
    if (error) setMessage({ text: `Could not import: ${error.message}`, error: true });
    else {
      await load();
      setMessage({ text: `Imported ${current.length} policies.` });
    }
    setBusy(false);
  }

  const form = (
    <div className="space-y-3">
      <div className="grid gap-3 sm:grid-cols-2">
        <label className="text-sm text-ink">Policy number
          <input value={draft.number} onChange={(e) => set("number", e.target.value)} className={inputCls} />
        </label>
        <label className="text-sm text-ink">Title
          <input value={draft.title} onChange={(e) => set("title", e.target.value)} className={inputCls} />
        </label>
        <label className="text-sm text-ink sm:col-span-2">One-line summary
          <input value={draft.summary || ""} onChange={(e) => set("summary", e.target.value)} className={inputCls} />
        </label>
        <div className="text-sm text-ink sm:col-span-2">
          <p className="font-medium">Policy file</p>
          {draft.file_path && draft.file_kind ? (
            <p className="mt-1 rounded-lg border border-gold-light/60 bg-white px-3 py-2 text-sm">
              Uploaded: <span className="font-medium">{draft.file_name || "file"}</span> ({draft.file_kind === "pdf" ? "PDF" : "Word"}).{" "}
              <button type="button" onClick={removeUpload} className="text-xs font-medium text-red-700 underline">Remove upload</button>
            </p>
          ) : (
            <label className="block">
              <span className="text-xs text-ink/65">Link to a file elsewhere (not needed if you upload one)</span>
              <input value={draft.file_url} onChange={(e) => set("file_url", e.target.value)} placeholder="https://… or /policies/…pdf" className={inputCls} />
            </label>
          )}
          <label className="mt-2 inline-flex cursor-pointer items-center gap-2 rounded-lg border border-gold-light bg-white px-3 py-1.5 text-xs font-medium text-ink/80 hover:bg-cream">
            {draft.file_path ? "Replace the file" : "Upload a PDF or Word file"}
            <input type="file" accept={UPLOAD_ACCEPT} className="sr-only" disabled={busy} onChange={(e) => { const f = e.target.files?.[0]; if (f) upload(f); e.target.value = ""; }} />
          </label>
          <p className="mt-1 text-xs text-ink/65">
            A PDF is best. A Word (.docx) file is offered to visitors as a Word download. Replacing the file makes everyone who must sign this policy sign the new version.
          </p>
        </div>
        <label className="text-sm text-ink">Category
          <select value={draft.category} onChange={(e) => set("category", e.target.value as Row["category"])} className={inputCls}>
            <option value="required">Required (DfE)</option>
            <option value="published">Published</option>
          </select>
        </label>
        <label className="text-sm text-ink">Parent question group
          <select value={draft.parent_question_category || ""} onChange={(e) => set("parent_question_category", e.target.value || null)} className={inputCls}>
            <option value="">None</option>
            {GROUPS.map((g) => <option key={g.key} value={g.key}>{g.label}</option>)}
          </select>
        </label>
        <label className="text-sm text-ink">Last reviewed
          <input type="date" value={draft.last_reviewed || ""} onChange={(e) => set("last_reviewed", e.target.value || null)} className={inputCls} />
        </label>
        <label className="text-sm text-ink">Review due
          <input type="date" value={draft.next_review || ""} onChange={(e) => set("next_review", e.target.value || null)} className={inputCls} />
        </label>
        <label className="text-sm text-ink">Display order
          <input type="text" inputMode="decimal" value={draft.order_index} onChange={(e) => set("order_index", Number(e.target.value))} className={inputCls} />
        </label>
        <label className="text-sm text-ink">Who can see it
          <select value={draft.visibility} onChange={(e) => set("visibility", e.target.value as Row["visibility"])} className={inputCls}>
            <option value="public">Everyone, listed on the website</option>
            <option value="staff">Staff only, for signing and compliance, not listed publicly</option>
          </select>
        </label>
        <label className="flex items-center gap-2 pt-6 text-sm text-ink">
          <input type="checkbox" checked={draft.featured} onChange={(e) => set("featured", e.target.checked)} />
          Show in &ldquo;Key documents&rdquo; at the top of the Policies page
        </label>
      </div>
      <div className="flex gap-2">
        <button type="button" onClick={save} disabled={busy} className="rounded-full bg-gold-700 px-4 py-1.5 text-xs font-semibold text-white hover:bg-gold-900 disabled:opacity-60">{busy ? "Working…" : "Save"}</button>
        <button type="button" onClick={() => setEditingId(null)} className="rounded-full border border-gold-light/60 px-4 py-1.5 text-xs text-ink/70 hover:bg-cream">Cancel</button>
      </div>
    </div>
  );

  return (
    <Card title="Policy documents" description="Everything on the website's Policies page is controlled here: which policies are listed (Show / Hide from website), their order, which appear in the Key documents box, their group heading, and the PDF each one opens. Staff-only policies stay here for signing and the compliance tracker without being listed publicly. Changes are live immediately, no rebuild. To choose which policies need a signature, use Documents & signatures.">
      {rows === null ? (
        <p className="text-sm text-ink/65">Loading…</p>
      ) : (
        <ul className="divide-y divide-gold-light/40 rounded-2xl border border-gold-light/50 bg-white">
          {live.map((r) => (
            <li key={r.id} className="p-3">
              {editingId === r.id ? (
                form
              ) : (
                <div className="flex flex-wrap items-center justify-between gap-3">
                  <div className="min-w-0">
                    <p className="text-sm text-ink">{r.number} &mdash; {r.title}</p>
                    <p className="text-xs text-ink/65">
                      {r.visibility === "staff" ? <span className="rounded-full bg-ink/5 px-2 py-0.5 font-semibold uppercase tracking-wide text-ink/70">Staff only</span> : <span className="rounded-full bg-gold-100 px-2 py-0.5 font-semibold uppercase tracking-wide text-gold-900">On website</span>}
                      {r.featured && <span className="ml-1 rounded-full bg-teal-700/10 px-2 py-0.5 font-semibold uppercase tracking-wide text-teal-700">Key document</span>}
                      {" · "}
                      {r.category === "required" ? "Required" : "Published"}
                      {r.next_review ? ` · review due ${new Date(r.next_review).toLocaleDateString("en-GB", { month: "short", year: "numeric" })}` : ""}
                      {" · "}
                      <a href={absoluteFileUrl(r.file_url)} target="_blank" rel="noreferrer" className="text-teal-700 hover:underline">{r.file_kind === "docx" ? "Word file" : "file"}</a>
                    </p>
                  </div>
                  <div className="flex shrink-0 flex-wrap gap-2">
                    <button type="button" aria-label={`Move ${r.title} up`} onClick={() => move(r, -1)} disabled={busy} className="rounded-full border border-gold-light px-2 py-1 text-xs text-ink/70 hover:bg-cream disabled:opacity-50">↑</button>
                    <button type="button" aria-label={`Move ${r.title} down`} onClick={() => move(r, 1)} disabled={busy} className="rounded-full border border-gold-light px-2 py-1 text-xs text-ink/70 hover:bg-cream disabled:opacity-50">↓</button>
                    <button type="button" onClick={() => setVisibility(r, r.visibility === "public" ? "staff" : "public")} disabled={busy} className="rounded-full border border-gold-light px-3 py-1 text-xs text-ink/75 hover:bg-cream disabled:opacity-50">
                      {r.visibility === "public" ? "Hide from website" : "Show on website"}
                    </button>
                    <button type="button" onClick={() => startEdit(r)} className="rounded-full border border-gold-500 px-3 py-1 text-xs text-gold-700 hover:bg-cream">Edit</button>
                    <button type="button" onClick={() => remove(r)} disabled={busy} className="rounded-full border border-red-300 px-3 py-1 text-xs text-red-700 hover:bg-red-50 disabled:opacity-50">Remove</button>
                  </div>
                </div>
              )}
            </li>
          ))}
          {live.length === 0 && (
            <li className="p-3 text-sm text-ink/65">
              No policies in the database yet.{" "}
              <button type="button" onClick={importCurrent} disabled={busy} className="font-medium text-teal-700 underline disabled:opacity-50">Import the current website policies</button>
            </li>
          )}
        </ul>
      )}

      {editingId === "new" ? (
        <div className="mt-3 rounded-2xl border border-gold-light/50 bg-cream/40 p-3">{form}</div>
      ) : (
        <button type="button" onClick={startNew} className="mt-3 rounded-full bg-gold-700 px-4 py-2 text-sm font-semibold text-white hover:bg-gold-900">Add new</button>
      )}

      {removed.length > 0 && (
        <div className="mt-4">
          <button type="button" onClick={() => setShowRemoved((v) => !v)} className="text-xs font-medium text-ink/65 underline">
            {showRemoved ? "Hide" : "Show"} removed ({removed.length})
          </button>
          {showRemoved && (
            <ul className="mt-2 divide-y divide-gold-light/40 rounded-2xl border border-gold-light/50 bg-white">
              {removed.map((r) => (
                <li key={r.id} className="flex items-center justify-between gap-3 p-3 text-sm text-ink/65">
                  <span>{r.number} &mdash; {r.title}</span>
                  <button type="button" onClick={() => restore(r)} disabled={busy} className="rounded-full border border-gold-light px-3 py-1 text-xs text-ink/75 hover:bg-cream disabled:opacity-50">Restore</button>
                </li>
              ))}
            </ul>
          )}
        </div>
      )}
      {message && <p className={`mt-2 text-sm ${message.error ? "text-red-700" : "text-ink/70"}`}>{message.text}</p>}
    </Card>
  );
}
