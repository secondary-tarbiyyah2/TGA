// Builds the portal demo: the real portal pages, with made-up data and no
// network, as one static page that can be hosted anywhere (for example as a
// claude.ai artifact). See docs/portal-demo.md.
//
//   npm run build:demo [-- <outDir>]      (default outDir: out-demo)
//
// The real site is never touched: the demo is built in a copy of the repo in a
// temporary folder, where
//   - src/app holds only a demo root layout and one page (the portal shell),
//   - the portal's pages move to src/portal-pages (so they are modules, not routes),
//   - next/link, next/navigation and @/lib/supabase/client point at src/lib/demo,
//   - code that reads or sets window.location is pointed at the #hash router.
// Then scripts/demo/postprocess.mjs makes every URL relative and renames _next.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const outDir = path.resolve(process.argv[2] || path.join(repo, "out-demo"));
const work = process.env.DEMO_WORK_DIR ? path.resolve(process.env.DEMO_WORK_DIR) : path.join(os.tmpdir(), "tga-portal-demo-build");
const log = (...a) => console.log("[demo]", ...a);

// ── 1. a working copy ─────────────────────────────────────────────────────
fs.rmSync(work, { recursive: true, force: true });
fs.mkdirSync(work, { recursive: true });
for (const item of ["src", "public", "content", "supabase/migrations", "supabase/functions", "package.json", "tsconfig.json", "postcss.config.mjs", "scripts/demo"]) {
  const from = path.join(repo, item);
  if (!fs.existsSync(from)) continue;
  fs.cpSync(from, path.join(work, item), { recursive: true, dereference: true });
}
fs.symlinkSync(fs.realpathSync(path.join(repo, "node_modules")), path.join(work, "node_modules"), "dir");

// ── 2. the schema the mock uses for embeds ────────────────────────────────
execFileSync(process.execPath, [path.join(work, "scripts/demo/schema.mjs"), work], { stdio: "inherit" });

// ── 3. portal pages become modules; the app is one page ───────────────────
const app = path.join(work, "src/app");
const pages = path.join(work, "src/portal-pages");
fs.mkdirSync(pages, { recursive: true });
fs.renameSync(path.join(app, "learn"), path.join(pages, "learn"));
for (const entry of fs.readdirSync(app)) {
  if (["globals.css", "fonts", "fonts.css", "fonts.ts"].includes(entry)) continue;
  fs.rmSync(path.join(app, entry), { recursive: true, force: true });
}

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]));
const learnRoot = path.join(pages, "learn");
const routes = walk(learnRoot)
  .filter((f) => /\/page\.tsx?$/.test(f))
  .map((f) => {
    const rel = path.relative(learnRoot, path.dirname(f)).split(path.sep).join("/");
    const routePath = rel ? `/${rel}` : "/";
    const layouts = [];
    let dir = path.dirname(f);
    const chain = [];
    while (dir.startsWith(learnRoot)) {
      chain.unshift(dir);
      if (dir === learnRoot) break;
      dir = path.dirname(dir);
    }
    for (const d of chain) for (const ext of ["tsx", "ts"]) if (fs.existsSync(path.join(d, `layout.${ext}`))) layouts.push(path.join(d, "layout"));
    return { routePath, page: f.replace(/\.tsx?$/, ""), layouts };
  })
  .sort((a, b) => a.routePath.localeCompare(b.routePath));
const mod = (abs) => `@/${path.relative(path.join(work, "src"), abs).split(path.sep).join("/")}`;
fs.writeFileSync(
  path.join(app, "page.tsx"),
  `"use client";
// Generated by scripts/demo/build.mjs: every portal page, loaded when opened.
import { DemoApp, type DemoRoute } from "@/lib/demo/DemoApp";

const routes: DemoRoute[] = [
${routes.map((r) => `  { path: ${JSON.stringify(r.routePath)}, page: () => import(${JSON.stringify(mod(r.page))}) as never, layouts: [${r.layouts.map((l) => `() => import(${JSON.stringify(mod(l))}) as never`).join(", ")}] },`).join("\n")}
];

export default function DemoPage() {
  return <DemoApp routes={routes} />;
}
`,
);
fs.writeFileSync(
  path.join(app, "layout.tsx"),
  `import type { Metadata, Viewport } from "next";
import "./globals.css";
import { fontVariables } from "./fonts";

export const metadata: Metadata = { title: "TGA Portal (demo)", description: "A demo of the Tarbiyyah Global Academy portal with a made-up school.", robots: { index: false, follow: false } };
export const viewport: Viewport = { themeColor: "#FFFFFF" };

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en-GB" className="h-full antialiased" style={fontVariables}>
      <head>
        <link rel="icon" href="./favicon.svg" type="image/svg+xml" />
      </head>
      <body className="min-h-full flex flex-col bg-background text-ink">
        <a href="#main" className="skip-link">Skip to content</a>
        <div className="flex flex-1 flex-col">{children}</div>
      </body>
    </html>
  );
}
`,
);
log(`${routes.length} portal pages`);

// ── 4. point address handling at the #hash router ─────────────────────────
const rewrites = [
  [/@\/app\/learn\//g, "@/portal-pages/learn/"],
  [/new URL\(window\.location\.href\)/g, "new URL((window as any).__demoLoc.fullHref)"],
  [/window\.location\.search/g, "(window as any).__demoLoc.search"],
  [/window\.location\.pathname/g, "(window as any).__demoLoc.pathname"],
  [/window\.location\.replace\(/g, "(window as any).__demoLoc.replace("],
  [/window\.location\.assign\(/g, "(window as any).__demoLoc.assign("],
  [/window\.location\.href\s*=(?!=)/g, "(window as any).__demoLoc.href ="],
  [/window\.history\.replaceState\(/g, "(window as any).__demoLoc.replaceState("],
  [/window\.history\.pushState\(/g, "(window as any).__demoLoc.pushState("],
  // The demo's router, links and data in place of Next's and Supabase's.
  [/from "next\/link"/g, 'from "@/lib/demo/link"'],
  [/from "next\/navigation"/g, 'from "@/lib/demo/navigation"'],
];
let touched = 0;
for (const f of walk(path.join(work, "src")).filter((f) => /\.tsx?$/.test(f) && !f.includes(`${path.sep}lib${path.sep}demo${path.sep}`))) {
  let s = fs.readFileSync(f, "utf8");
  const before = s;
  for (const [re, to] of rewrites) s = s.replace(re, to);
  if (s !== before) {
    fs.writeFileSync(f, s);
    touched++;
  }
}
log(`address handling pointed at the hash router in ${touched} files`);
fs.writeFileSync(path.join(work, "src/lib/supabase/client.ts"), `// Portal demo build: the in-browser mock in place of Supabase.\nexport * from "@/lib/demo/client";\n`);

// ── 5. next.config for the demo ───────────────────────────────────────────
fs.writeFileSync(
  path.join(work, "next.config.mjs"),
  `export default {
  output: "export",
  images: { unoptimized: true },
  trailingSlash: false,
  productionBrowserSourceMaps: false,
  typescript: { ignoreBuildErrors: true },
  webpack(config, { isServer, webpack }) {
    if (!isServer) {
      config.devtool = false;
      // Fewer, larger files: the host allows a limited number.
      config.plugins.push(new webpack.optimize.LimitChunkCountPlugin({ maxChunks: 60 }));
    }
    return config;
  },
};
`,
);

// ── 6. build ──────────────────────────────────────────────────────────────
const env = {
  ...process.env,
  NEXT_PUBLIC_DEMO: "1",
  NEXT_PUBLIC_SUPABASE_URL: "https://demo.tga-portal.invalid",
  NEXT_PUBLIC_SUPABASE_ANON_KEY: "demo-anon-key",
  NEXT_TELEMETRY_DISABLED: "1",
  NODE_OPTIONS: `${process.env.NODE_OPTIONS || ""} --max-old-space-size=6144`.trim(),
};
log("next build (webpack) ...");
execFileSync(process.execPath, [path.join(work, "node_modules/next/dist/bin/next"), "build", "--webpack"], { cwd: work, env, stdio: "inherit" });

// ── 7. relative URLs, no "_" paths ────────────────────────────────────────
execFileSync(process.execPath, [path.join(work, "scripts/demo/postprocess.mjs"), path.join(work, "out"), outDir, path.join(work, "public")], { stdio: "inherit" });
