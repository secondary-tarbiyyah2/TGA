// Builds src/lib/learn/mushafPages.ts (where each of the 604 Madinah mushaf pages starts) from the
// page files in public/mushaf. Run: node scripts/build-mushaf-index.mjs
// The text in public/mushaf is the King Fahd Glorious Qur'an Printing Complex's Uthmanic Hafs v18 data,
// unchanged apart from the ayah numbers (the page draws its own). See docs/mushaf.md.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const dir = new URL("../public/mushaf/", import.meta.url);
const pages = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) Object.assign(pages, JSON.parse(readFileSync(new URL(f, dir), "utf8")).pages);
const nums = Object.keys(pages).map(Number).sort((a, b) => a - b);
if (nums.length !== 604 || nums[0] !== 1 || nums[603] !== 604) throw new Error(`expected pages 1-604, found ${nums.length}`);
let count = 0;
let prev = [0, 0];
for (const p of nums) {
  for (const [s, a] of pages[p]) {
    if (s < prev[0] || (s === prev[0] && a !== prev[1] + 1) || (s > prev[0] && a !== 1)) throw new Error(`out of order at page ${p}: ${s}:${a}`);
    prev = [s, a];
    count++;
  }
}
if (count !== 6236) throw new Error(`expected 6236 ayat, found ${count}`);
const starts = nums.map((p) => pages[p][0].slice(0, 2));
const body = `// Generated by scripts/build-mushaf-index.mjs from public/mushaf. Do not edit by hand.
// PAGE_START[p - 1] is [surah, ayah] of the first ayah on page p of the 604-page Madinah mushaf.
export const PAGE_START: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(starts)};
`;
writeFileSync(new URL("../src/lib/learn/mushafPages.ts", import.meta.url), body);
console.log("pages 604, ayat", count);
